function GrowthRate(array) {
    return 1 + (array[array.length - 1] - array[array.length - 2]) / array[array.length - 2]
}

function CurrentData(mode, index) {
    let data = FuelData.slice(FuelData.length - (12 + index), FuelData.length - index)
    return data.map((period) => {
        let set = [
            mode === "forecast" ? `${period.Month}\n${Number(period.Year) + 1}` : `${period.Month}\n${period.Year}`,
            period.Solid,
            period.Gas,
            period.Liquid,
            period.Electricity
        ]
        return set;
    })
}

function ForecastData() {
    let data = CurrentData("forecast", 0)
    
    let solidData = data.map((obj) => {return Math.ceil(Number(obj[1]))})
    let gasData = data.map((obj) => {return Math.ceil(Number(obj[2]))})
    let liquidData = data.map((obj) => {return Math.ceil(Number(obj[3]))})
    let electricityData = data.map((obj) => {return Math.ceil(Number(obj[4]))})

    let result = [data[data.length - 1]]

    for (let i = 0; i < 12; i++) {
        if (result.length < 2) {
            result.push([data[0][0], Number(solidData[solidData.length - 1] * GrowthRate(solidData)), Number(gasData[gasData.length - 1] * GrowthRate(gasData)), Number(liquidData[liquidData.length - 1] * GrowthRate(liquidData)), Number(electricityData[electricityData.length - 1] * GrowthRate(electricityData))])
        }
        else {
            solidData = result.map((obj) => {return Math.ceil(Number(obj[1]))})
            gasData = result.map((obj) => {return Math.ceil(Number(obj[2]))})
            liquidData = result.map((obj) => {return Math.ceil(Number(obj[3]))})
            electricityData = result.map((obj) => {return Math.ceil(Number(obj[4]))})

            result.push([data[i][0], Number(solidData[solidData.length - 1] * GrowthRate(solidData)), Number(gasData[gasData.length - 1] * GrowthRate(gasData)), Number(liquidData[liquidData.length - 1] * GrowthRate(liquidData)), Number(electricityData[electricityData.length - 1] * GrowthRate(electricityData))])
        }
    }

    return result.slice(1)
}